/**
 * Finds a theme object by English slug or Bengali slug or ID
 */
function getThemeBySlug(slug) {
  if (!slug) return null;
  const decoded = decodeURIComponent(slug).trim().toLowerCase();
  return LITERARY_THEMES.find(t => 
    t.slug.toLowerCase() === decoded || 
    t.bengaliSlug.toLowerCase() === decoded || 
    t.id.toLowerCase() === decoded ||
    t.name.toLowerCase() === decoded
  ) || null;
}

module.exports = {
  LITERARY_THEMES,
  getThemeBySlug
};
